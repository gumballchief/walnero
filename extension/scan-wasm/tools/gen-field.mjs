// Writes src/field_gen.rs: the field multiply and square as flat code, no loops and no arrays. Browsers compile this far better.
// It works limb by limb and carries as it goes, so few values are alive at once and little spills to memory.
import fs from 'node:fs';

const pairs = (level, square) => {
  const out = [];
  for (let i = 0; i < 5; i++) {
    const j = level - i;
    if (j < 0 || j > 4) continue;
    if (square && j < i) continue;
    out.push([i, j]);
  }
  return out;
};

const lines = [];
const emit = (s) => lines.push('    ' + s);

// Sums one level of products. Returns names of the unbiased low and high sums, doubling the off-diagonal terms when squaring.
function level(tag, m, square) {
  const ps = pairs(m, square);
  if (!ps.length) return null;
  const a = (i) => `a${i}`;
  const b = (j) => (square ? `a${j}` : `b${j}`);
  const diag = square ? ps.filter(([i, j]) => i === j) : [];
  const off = square ? ps.filter(([i, j]) => i !== j) : ps;
  const parts = { lo: [], hi: [] };
  const sum = (list, name) => {
    if (!list.length) return null;
    list.forEach(([i, j], n) => {
      emit(`let (h${tag}${name}${n}, l${tag}${name}${n}) = prod(${a(i)}, ${b(j)}, c1, c2);`);
    });
    const fold = (kind, bias) => {
      let expr = `${kind}${tag}${name}0`;
      for (let n = 1; n < list.length; n++) expr = `add64(${expr}, ${kind}${tag}${name}${n})`;
      return `sub64(${expr}, u64x2_splat(${list.length}u64.wrapping_mul(${bias})))`;
    };
    emit(`let lo${tag}${name} = ${fold('l', 'B3')};`);
    emit(`let hi${tag}${name} = ${fold('h', 'B1')};`);
    return [`lo${tag}${name}`, `hi${tag}${name}`];
  };
  const o = sum(off, 'o');
  const d = sum(diag, 'd');
  const doubled = (x) => (square ? `add64(${x}, ${x})` : x);
  const lo = [o && doubled(o[0]), d && d[0]].filter(Boolean);
  const hi = [o && doubled(o[1]), d && d[1]].filter(Boolean);
  const join = (xs) => xs.reduce((acc, x) => `add64(${acc}, ${x})`);
  emit(`let lo${tag} = ${join(lo)};`);
  emit(`let hi${tag} = ${join(hi)};`);
  return { lo: `lo${tag}`, hi: `hi${tag}` };
}

function body(square) {
  emit('let c1 = splat(C1);');
  emit('let c2 = splat(C2);');
  emit('let round = i64x2_splat(1 << 50);');
  emit('let [a0, a1, a2, a3, a4] = a.0;');
  if (!square) emit('let [b0, b1, b2, b3, b4] = b.0;');
  let carryIn = null;
  for (let m = 0; m <= 4; m++) {
    const low = level(`m${m}`, m, square);
    const high = m <= 3 ? level(`h${m}`, m + 5, square) : null;
    let expr = low.lo;
    if (high) expr = `add64(${expr}, times19(${high.lo}))`;
    if (carryIn) expr = `add64(${expr}, ${carryIn})`;
    emit(`let (r${m}, q${m}) = carry(${expr}, round);`);
    if (m < 4) {
      let next = `add64(q${m}, ${low.hi})`;
      if (high) next = `add64(${next}, times19(${high.hi}))`;
      emit(`let in${m + 1} = ${next};`);
      carryIn = `in${m + 1}`;
    } else {
      emit(`let (r0, q5) = carry(add64(r0, times19(add64(q4, ${low.hi}))), round);`);
      emit('let (r1, q6) = carry(add64(r1, q5), round);');
      emit('let r2 = add64(r2, q6);');
    }
  }
  emit('let bias = u64x2_splat(B3);');
  emit('let c3 = splat(C3);');
  emit('F([f64x2_sub(add64(r0, bias), c3), f64x2_sub(add64(r1, bias), c3), f64x2_sub(add64(r2, bias), c3), f64x2_sub(add64(r3, bias), c3), f64x2_sub(add64(r4, bias), c3)])');
}

lines.push('// Generated by tools/gen-field.mjs. Do not edit by hand.');
lines.push('#[inline(never)]', 'fn mul(a: &F, b: &F) -> F {');
body(false);
lines.push('}', '', '#[inline(never)]', 'fn sqr(a: &F) -> F {');
body(true);
lines.push('}', '');
fs.writeFileSync(new URL('../src/field_gen.rs', import.meta.url), lines.join('\n'));
